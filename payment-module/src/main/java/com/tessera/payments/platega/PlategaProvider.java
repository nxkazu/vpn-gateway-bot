package com.tessera.payments.platega;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.tessera.core.api.CreatedInvoice;
import com.tessera.core.api.InvoiceStatus;
import com.tessera.core.api.PaymentProvider;
import com.tessera.core.api.PaymentRequest;
import com.tessera.payments.PaymentsConfig;
import okhttp3.MediaType;
import okhttp3.OkHttpClient;
import okhttp3.Request;
import okhttp3.RequestBody;
import okhttp3.Response;

import java.io.IOException;
import java.math.BigDecimal;
import java.util.concurrent.TimeUnit;

/**
 * Platega merchant gate (SBP / cards), implemented against the official API docs
 * (https://docs.platega.io). Transactions are created via {@code POST /transaction/process}
 * (X-MerchantId / X-Secret headers); the transaction id is generated by Platega and
 * returned as {@code transactionId}. Status is confirmed by polling
 * {@code GET /transaction/{id}} — no public callback endpoint is required, which keeps
 * the bot long-polling only.
 *
 * Status enum per docs: PENDING, CANCELED, CONFIRMED, CHARGEBACKED.
 */
public final class PlategaProvider implements PaymentProvider {

    private static final MediaType JSON = MediaType.get("application/json; charset=utf-8");

    private final PaymentsConfig.PlategaSection cfg;
    private final ObjectMapper mapper = new ObjectMapper();
    private final OkHttpClient http = new OkHttpClient.Builder()
            .connectTimeout(10, TimeUnit.SECONDS)
            .readTimeout(30, TimeUnit.SECONDS)
            .build();

    public PlategaProvider(PaymentsConfig.PlategaSection cfg) {
        this.cfg = cfg;
    }

    @Override
    public String id() {
        return "platega";
    }

    @Override
    public String displayName() {
        return "\uD83D\uDCB3 Platega (\u0421\u0411\u041F/\u043A\u0430\u0440\u0442\u044B)";
    }

    @Override
    public CreatedInvoice createInvoice(PaymentRequest req) throws Exception {
        ObjectNode details = mapper.createObjectNode();
        // Platega expects the amount in whole currency units (rubles), not kopecks.
        details.put("amount", new BigDecimal(req.amountMinor()).movePointLeft(2));
        details.put("currency", req.currency());

        // Anti-fraud metadata (required for some merchant categories; harmless otherwise).
        ObjectNode metadata = mapper.createObjectNode();
        metadata.put("userId", String.valueOf(req.telegramId()));
        metadata.put("userName", "tg_" + req.telegramId());

        ObjectNode body = mapper.createObjectNode();
        // NOTE: do NOT send an "id" field — the transaction id is generated by Platega.
        body.put("paymentMethod", cfg.getPaymentMethod());
        body.set("paymentDetails", details);
        body.put("description", req.description());
        body.put("return", req.returnUrl());
        body.put("failedUrl", req.returnUrl());
        body.put("payload", req.telegramId() + ":" + req.planCode());
        body.set("metadata", metadata);

        Request request = new Request.Builder()
                .url(cfg.getBaseUrl() + "/transaction/process")
                .header("X-MerchantId", cfg.getMerchantId())
                .header("X-Secret", cfg.getSecret())
                .post(RequestBody.create(body.toString(), JSON))
                .build();
        JsonNode root = execute(request);
        String transactionId = root.path("transactionId").asText(null);
        String redirect = root.path("redirect").asText(null);
        if (transactionId == null || transactionId.isBlank()) {
            throw new IOException("Platega did not return a transactionId: " + root);
        }
        if (redirect == null || redirect.isBlank()) {
            throw new IOException("Platega did not return a redirect URL: " + root);
        }
        return new CreatedInvoice(transactionId, redirect);
    }

    @Override
    public InvoiceStatus checkInvoice(String externalId) throws Exception {
        Request request = new Request.Builder()
                .url(cfg.getBaseUrl() + "/transaction/" + externalId)
                .header("X-MerchantId", cfg.getMerchantId())
                .header("X-Secret", cfg.getSecret())
                .get()
                .build();
        JsonNode root = execute(request);
        return mapStatus(root.path("status").asText(""));
    }

    /** Maps the documented Platega status enum onto the provider-neutral one. */
    static InvoiceStatus mapStatus(String status) {
        return switch (status) {
            case "CONFIRMED" -> InvoiceStatus.PAID;
            case "CANCELED", "CHARGEBACKED" -> InvoiceStatus.FAILED;
            case "PENDING" -> InvoiceStatus.PENDING;
            default -> InvoiceStatus.PENDING;
        };
    }

    private JsonNode execute(Request request) throws IOException {
        try (Response response = http.newCall(request).execute()) {
            String text = response.body() != null ? response.body().string() : "";
            if (!response.isSuccessful()) {
                throw new IOException("Platega API error " + response.code() + ": " + text);
            }
            return mapper.readTree(text);
        }
    }
}